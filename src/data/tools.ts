/* ============================================================
 * Merged registry — legacy tools + new unified tools
 * ============================================================ */
function withDeepDives(t: Tool): Tool {
  const external = deepDives[t.id];
  if (!external || external.length === 0) return t;
  const inline = t.deepDive ?? [];
  return {
    ...t,
    deepDive: [...inline, ...external],
  };
}

